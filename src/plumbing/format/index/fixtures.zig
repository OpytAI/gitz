/// Synthetic fixtures covering versions 2, 3, and 4 (go-git want map).
pub const all = [_]Fixture{
    .{ .name = "v2_simple", .version = 2, .data = &v2_simple_raw },
    .{ .name = "v3_intent", .version = 3, .data = &v3_intent_raw },
    .{ .name = "v4_prefix", .version = 4, .data = &v4_prefix_raw },
};

test "fixtures cover versions 2 3 4" {
    var seen: [5]bool = .{false} ** 5;
    for (all) |fx| {
        try std.testing.expect(fx.version >= 2 and fx.version <= 4);
        seen[fx.version] = true;
    }
    try std.testing.expect(seen[2]);
    try std.testing.expect(seen[3]);
    try std.testing.expect(seen[4]);
}

test "fixture images have DIRC header matching version and valid trailer" {
    // Embedded fixtures are SHA-1 indexes (default object format).
    const n = hash_pkg.digestSize();
    for (all) |fx| {
        const raw = fx.data;
        try std.testing.expect(raw.len >= 12 + n);
        try std.testing.expectEqualSlices(u8, "DIRC", raw[0..4]);
        try std.testing.expectEqual(fx.version, std.mem.readInt(u32, raw[4..8], .big));
        var h = hash_pkg.new(hash_pkg.objectFormat());
        h.update(raw[0 .. raw.len - n]);
        var sum: [hash_pkg.MaxSize]u8 = undefined;
        h.final(sum[0..n]);
        try std.testing.expectEqualSlices(u8, sum[0..n], raw[raw.len - n ..]);
    }
}
